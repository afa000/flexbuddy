-- Keep acknowledgements after block deletion so a delayed outbox retry cannot recreate data.
-- No request body or block snapshot is stored. Account deletion removes these receipts too.
create table api_write_receipt (
    id bigint generated by default as identity primary key,
    owner_id bigint not null references app_users(id) on delete cascade,
    request_key varchar(36) not null,
    request_hash varchar(64) not null,
    shift_id bigint not null,
    constraint uk_api_write_owner_key unique (owner_id, request_key)
);
