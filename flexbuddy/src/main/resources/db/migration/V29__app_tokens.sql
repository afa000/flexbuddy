create table app_token (
    id bigint generated by default as identity primary key,
    owner_id bigint not null references app_users(id),
    token_hash varchar(64) not null unique,
    device_name varchar(80),
    created_at timestamp with time zone not null,
    last_used_at timestamp with time zone not null,
    expires_at timestamp with time zone not null
);
create index app_token_owner on app_token(owner_id);
create index app_token_expiry on app_token(expires_at);

create table app_sign_in_challenge (
    id bigint generated by default as identity primary key,
    owner_id bigint not null references app_users(id),
    challenge_hash varchar(64) not null unique,
    purpose varchar(20) not null check (purpose in ('VERIFY_EMAIL', 'TWO_FACTOR')),
    device_name varchar(80),
    created_at timestamp with time zone not null,
    expires_at timestamp with time zone not null
);
create index app_challenge_owner on app_sign_in_challenge(owner_id);
create index app_challenge_expiry on app_sign_in_challenge(expires_at);
